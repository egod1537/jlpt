function parseCsv(input) {
  const rows = [];
  let row = [];
  let field = "";
  let inQuotes = false;

  for (let index = 0; index < input.length; index += 1) {
    const char = input[index];
    const nextChar = input[index + 1];

    if (inQuotes) {
      if (char === "\"" && nextChar === "\"") {
        field += "\"";
        index += 1;
      } else if (char === "\"") {
        inQuotes = false;
      } else {
        field += char;
      }
      continue;
    }

    if (char === "\"") {
      inQuotes = true;
    } else if (char === ",") {
      row.push(field);
      field = "";
    } else if (char === "\n") {
      row.push(field.replace(/\r$/, ""));
      rows.push(row);
      row = [];
      field = "";
    } else {
      field += char;
    }
  }

  if (field.length > 0 || row.length > 0) {
    row.push(field.replace(/\r$/, ""));
    rows.push(row);
  }

  return rows;
}

function normalizeWhitespace(value) {
  return value
    .replace(/\uFEFF/g, "")
    .replace(/\u3000/g, " ")
    .replace(/[‘’]/g, "'")
    .replace(/[“”]/g, "\"")
    .replace(/\s+/g, " ")
    .trim();
}

function stripLatinNoise(value) {
  return value
    .replace(/[ᄀ-ᇿㄱ-ㅎㅏ-ㅣ]/g, " ")
    .replace(/[A-Za-z]+[A-Za-z0-9]*/g, " ")
    .replace(/\b\d+\b/g, " ")
    .replace(/[@#$%&=_+|[\]{}<>]/g, " ");
}

function stripOcrBullets(value, sourceFile = "") {
  const isOcrSource = sourceFile === "~115.csv" || sourceFile === "~139.csv";

  let nextValue = value
    .replace(/^・\s*/u, "")
    .replace(/\s*ーー+.*$/u, "")
    .replace(/\s*一一+.*$/u, "");

  if (isOcrSource) {
    nextValue = nextValue
      .replace(/^[ロ口]{1,3}\s*/u, "")
      .replace(/^[ロ口]{1,3}(?=[ぁ-ゖァ-ヺ一-龯（(])/u, "")
      .replace(/^コ\s*(?=[一-龯])/u, "")
      .replace(/^ビ\s*(?=[ぁ-ゖ一-龯])/u, "");
  }

  return nextValue;
}

function cleanJapanese(value, sourceFile) {
  const normalized = stripOcrBullets(
    stripLatinNoise(normalizeWhitespace(value)),
    sourceFile,
  )
    .replace(/[」『』"@]/g, " ")
    .replace(/\s+/g, " ")
    .trim();

  const beforeOpenParen = finalizeJapanese(
    normalized.split(/[（(]/u)[0] ?? "",
  );

  if (
    beforeOpenParen.length > 0 &&
    !beforeOpenParen.includes(")") &&
    isLikelyStandaloneJapanese(beforeOpenParen)
  ) {
    return beforeOpenParen;
  }

  const targetSegment = getBestJapaneseSegment(normalized);

  if (targetSegment.length > 0) {
    return targetSegment;
  }

  const beforeContext = normalized.split(/[（(]/)[0]?.trim() ?? normalized;
  const compacted = beforeContext.length > 0 ? beforeContext : normalized;

  return finalizeJapanese(compacted);
}

function finalizeJapanese(value) {
  return compactJapaneseSpacing(value)
    .replace(/\s+(?=[）)])/g, "")
    .replace(/[(（]\s*$/g, "")
    .replace(/[）)]+\s*$/g, "")
    .replace(/^[,.;:\-–—]+|[,.;:\-–—]+$/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

function compactJapaneseSpacing(value) {
  let previous = value;
  let next = previous.replace(/([ぁ-ゖァ-ヺー])\s+(?=[ぁ-ゖァ-ヺー])/gu, "$1");

  while (next !== previous) {
    previous = next;
    next = previous.replace(/([ぁ-ゖァ-ヺー])\s+(?=[ぁ-ゖァ-ヺー])/gu, "$1");
  }

  return next;
}

function getBestJapaneseSegment(value) {
  const segments = value
    .split(/[）)]/u)
    .slice(1)
    .map((segment) => {
      const segmentBeforeContext = segment.split(/[（(]/u)[0] ?? "";

      return finalizeJapanese(segmentBeforeContext);
    })
    .filter(isLikelyStandaloneJapanese);

  return segments.sort((a, b) => b.length - a.length)[0] ?? "";
}

function cleanReading(value, fallback, sourceFile) {
  const cleaned = stripOcrBullets(
    stripLatinNoise(normalizeWhitespace(value)),
    sourceFile,
  )
    .replace(/[^\u3040-\u309f\u30a0-\u30ffー・（）() 〜～]/g, " ")
    .replace(/\s+/g, " ")
    .trim();

  return compactJapaneseSpacing(cleaned || fallback);
}

function cleanKorean(value) {
  const beforeDefinitionMarker = normalizeWhitespace(value).split(/\s*[=＝]\s*/)[0];
  const withoutForeignText = stripLatinNoise(beforeDefinitionMarker)
    .replace(/[ー―—–]+.*$/u, " ")
    .replace(/[一]{2,}.*$/u, " ")
    .replace(/[ぁ-ゖァ-ヺ一-龯]/g, " ")
    .replace(/[()（）"“”'`]/g, " ")
    .replace(/[「」『』\[\]{}<>|@#$%&=_+~]/g, " ")
    .replace(/[;；]/g, "; ")
    .replace(/[,.，。]/g, ", ")
    .replace(/[!！?？]/g, " ")
    .replace(/\s+/g, " ")
    .trim();

  return applyKoreanReplacements(joinBrokenKoreanSyllables(withoutForeignText))
    .replace(/\s*,\s*/g, ", ")
    .replace(/\s*;\s*/g, "; ")
    .replace(/\s+/g, " ")
    .replace(/^[,.;:\-–—]+|[,.;:\-–—]+$/g, "")
    .trim();
}

function applyKoreanReplacements(value) {
  return KOREAN_TEXT_REPLACEMENTS.reduce(
    (nextValue, [pattern, replacement]) => nextValue.replace(pattern, replacement),
    value,
  );
}

function joinBrokenKoreanSyllables(value) {
  const tokens = value.split(" ");
  const output = [];
  let singleSyllableRun = [];

  tokens.forEach((token) => {
    if (/^[가-힣]$/.test(token)) {
      singleSyllableRun.push(token);
      return;
    }

    flushSingleSyllables(output, singleSyllableRun);
    singleSyllableRun = [];
    output.push(token);
  });

  flushSingleSyllables(output, singleSyllableRun);

  return output.join(" ");
}

function flushSingleSyllables(output, run) {
  if (run.length === 0) {
    return;
  }

  output.push(run.length >= 2 ? run.join("") : run[0]);
}

function isLikelyStandaloneJapanese(value) {
  return (
    value.length >= 2 &&
    value.length <= 12 &&
    /^[ぁ-ゖァ-ヺ一-龯ー・（）()]+$/u.test(value) &&
    !/^(を|に|が|は|へ|で|と|も|や|の|する)$/u.test(value)
  );
}

function applyWordCorrections(word, sourceRow) {
  const correction = ROW_CORRECTIONS.get(String(sourceRow.csvLine));
  const correctionFlags = [];

  if (correction === undefined) {
    return correctionFlags;
  }

  ["jp", "rd", "kr"].forEach((key) => {
    if (correction[key] !== undefined && word[key] !== correction[key]) {
      word[key] = correction[key];
      correctionFlags.push(`corrected-${key}`);
    }
  });

  return correctionFlags;
}

function applyLexicalCorrections(word) {
  const correction = LEXICAL_CORRECTIONS.get(word.jp);
  const correctionFlags = [];

  if (correction === undefined) {
    return correctionFlags;
  }

  ["rd", "kr"].forEach((key) => {
    if (correction[key] !== undefined && word[key] !== correction[key]) {
      word[key] = correction[key];
      correctionFlags.push(`corrected-${key}`);
    }
  });

  return correctionFlags;
}

function getQualityFlags(word, sourceRow, correctionFlags) {
  const flags = [];
  const isNoisySource =
    sourceRow.sourceFile === "~115.csv" || sourceRow.sourceFile === "~139.csv";
  const sourceText = [sourceRow.jp, sourceRow.rd, sourceRow.kr].join(" ");
  const hasCorrectedJapanese = correctionFlags.includes("corrected-jp");
  const hasCorrectedReading = correctionFlags.includes("corrected-rd");
  const hasCorrectedMeaning = correctionFlags.includes("corrected-kr");
  const isLexicallyKnown = LEXICAL_CORRECTIONS.has(word.jp);

  if (word.jp.length === 0 || word.kr.length === 0) {
    flags.push("needs-manual-review");
  }

  if (correctionFlags.length > 0) {
    flags.push(...correctionFlags, "auto-corrected");
  }

  if (/[A-Za-zᄀ-ᇿㄱ-ㅎㅏ-ㅣ@#$%&=_+|[\]{}<>]/.test(sourceRow.jp)) {
    flags.push("cleaned-japanese-ocr-noise");
  }

  if (/[A-Za-zᄀ-ᇿㄱ-ㅎㅏ-ㅣぁ-ゖァ-ヺ一-龯@#$%&=_+|[\]{}<>]/.test(sourceRow.kr)) {
    flags.push("cleaned-meaning-ocr-noise");
  }

  if (
    isNoisySource &&
    !hasCorrectedMeaning &&
    !isLexicallyKnown &&
    isSuspiciousMeaning(word.kr)
  ) {
    flags.push("meaning-needs-review");
  }

  if (
    isNoisySource &&
    !hasCorrectedJapanese &&
    !isLexicallyKnown &&
    isSuspiciousJapanese(word.jp)
  ) {
    flags.push("word-needs-review");
  }

  if (
    isNoisySource &&
    !hasCorrectedReading &&
    !isLexicallyKnown &&
    isSuspiciousReading(word.rd)
  ) {
    flags.push("reading-needs-review");
  }

  if (isNoisySource && /[ᄀ-ᇿㄱ-ㅎㅏ-ㅣA-Za-z]|[0-9]{2,}|[<>{}[\]@#$%&=_+|]/.test(sourceText)) {
    flags.push("source-contained-ocr-noise");
  }

  return flags;
}

function isSuspiciousMeaning(value) {
  return (
    value.length <= 1 ||
    /^(이|그|수|더|고|개|배|때|트|없다|같다|보다|하부|직전|정비|저공|사욕|제방|서포|차오|단심|비로|여르|분)$/.test(value)
  );
}

function isSuspiciousJapanese(value) {
  return (
    (value.length <= 1 && !/[一-龯]/u.test(value)) ||
    /\s/.test(value) ||
    /[A-Za-zᄀ-ᇿㄱ-ㅎㅏ-ㅣ@#$%&=_+|[\]{}<>]/.test(value) ||
    /^[ぁ-ゖー]{1,2}$/.test(value) ||
    /^[ァ-ヺー]{1,2}$/.test(value)
  );
}

function isSuspiciousReading(value) {
  return (
    value.length <= 1 ||
    /[A-Za-zᄀ-ᇿㄱ-ㅎㅏ-ㅣ@#$%&=_+|[\]{}<>]/.test(value) ||
    /^[ぁ-ゖー]{1,2}$/.test(value) ||
    /^[ァ-ヺー]{1,2}$/.test(value)
  );
}

function needsReview(qualityFlags) {
  return qualityFlags.some((flag) => REVIEW_REQUIRED_FLAGS.has(flag));
}

function buildRows(csvText) {
  const [header, ...dataRows] = parseCsv(csvText.replace(/^\uFEFF/, ""));
  const headerIndex = Object.fromEntries(
    header.map((columnName, index) => [normalizeWhitespace(columnName), index]),
  );

  return dataRows.map((row, index) => ({
    csvLine: index + 2,
    jp: normalizeWhitespace(row[headerIndex["일본어"]] ?? ""),
    rd: normalizeWhitespace(row[headerIndex["읽기"]] ?? ""),
    kr: normalizeWhitespace(row[headerIndex["뜻"]] ?? ""),
    sourceFile: normalizeWhitespace(row[headerIndex["출처파일"]] ?? ""),
  }));
}

function increment(map, key) {
  map[key] = (map[key] ?? 0) + 1;
}

function preprocess() {
  const rows = buildRows(readFileSync(SOURCE_PATH, "utf8"));
  const accepted = [];
  const rejectCounts = {};
  const sourceCounts = {};
  const qualityCounts = {};
  let autoCorrectedCount = 0;
  let needsReviewCount = 0;
  const autoCorrectedSamples = [];
  const reviewSamples = [];

  rows.forEach((row) => {
    if (row.jp.length === 0 || row.kr.length === 0) {
      increment(
        rejectCounts,
        row.jp.length === 0 ? "missing-japanese" : "missing-meaning",
      );
      return;
    }

    const jp = cleanJapanese(row.jp, row.sourceFile);
    const rd = cleanReading(row.rd, jp || row.jp, row.sourceFile);
    const kr = cleanKorean(row.kr) || row.kr;
    const cleanedWord = { jp: jp || row.jp, rd, kr };
    const correctionFlags = [
      ...applyWordCorrections(cleanedWord, row),
      ...applyLexicalCorrections(cleanedWord),
    ];
    const qualityFlags = getQualityFlags(cleanedWord, row, correctionFlags);
    const hasAutoCorrection = qualityFlags.includes("auto-corrected");
    const requiresReview = needsReview(qualityFlags);
    const word = {
      n: accepted.length + 1,
      ...cleanedWord,
      ...(qualityFlags.length > 0
        ? {
            qualityFlags,
          }
        : {}),
    };

    if (requiresReview) {
      word.needsReview = true;
      needsReviewCount += 1;
    }

    if (hasAutoCorrection) {
      autoCorrectedCount += 1;
    }

    accepted.push(word);
    increment(sourceCounts, row.sourceFile || "unknown");
    qualityFlags.forEach((flag) => increment(qualityCounts, flag));

    if (hasAutoCorrection && autoCorrectedSamples.length < 160) {
      autoCorrectedSamples.push({
        csvLine: row.csvLine,
        sourceFile: row.sourceFile,
        original: { jp: row.jp, rd: row.rd, kr: row.kr },
        cleaned: word,
        qualityFlags,
      });
    }

    if (requiresReview && reviewSamples.length < 160) {
      reviewSamples.push({
        csvLine: row.csvLine,
        sourceFile: row.sourceFile,
        original: { jp: row.jp, rd: row.rd, kr: row.kr },
        cleaned: word,
        qualityFlags,
      });
    }
  });

  writeFileSync(OUTPUT_PATH, `${JSON.stringify(accepted, null, 2)}\n`);
  writeFileSync(
    REPORT_PATH,
    `${JSON.stringify(
      {
        acceptedCount: accepted.length,
        rejectedCount: rows.length - accepted.length,
        autoCorrectedCount,
        needsReviewCount,
        rejectCounts,
        sourceCounts,
        qualityCounts,
        autoCorrectedSamples,
        reviewSamples,
      },
      null,
      2,
    )}\n`,
  );

  console.log(`accepted ${accepted.length} N1 words`);
  console.log(`rejected ${rows.length - accepted.length} rows`);
  console.log(`wrote ${OUTPUT_PATH}`);
  console.log(`wrote ${REPORT_PATH}`);
}

